def shuffled_copy(items, seed):
    """
    使用固定种子打乱顺序。

    同一份代码每次启动都会生成相同顺序，
    因此同一天重复运行时，文案保持一致。
    """
    result = list(items)
    random.Random(seed).shuffle(result)
    return result


SHUFFLED_TITLES = shuffled_copy(
    TITLES,
    "evening-ad-titles-v2",
)

SHUFFLED_MESSAGES = shuffled_copy(
    MESSAGES,
    "evening-ad-messages-v2",
)

SHUFFLED_ENDINGS = shuffled_copy(
    ENDINGS,
    "evening-ad-endings-v2",
)


def select_content(today):
    """
    按自然日从打乱后的列表中轮换。

    标题每 40 个自然日循环一次。
    正文每 100 个自然日循环一次。
    非工作日不推送，也不补发当天的文案。
    """
    day_index = today.toordinal()

    title = SHUFFLED_TITLES[
        day_index % len(SHUFFLED_TITLES)
    ]

    body = SHUFFLED_MESSAGES[
        day_index % len(SHUFFLED_MESSAGES)
    ]

    # 每完成一轮正文，更换结尾搭配的偏移量。
    message_cycle = day_index // len(SHUFFLED_MESSAGES)

    ending = SHUFFLED_ENDINGS[
        (day_index + message_cycle) % len(SHUFFLED_ENDINGS)
    ]

    return title, body, ending


def build_card():
    now = datetime.now(ZoneInfo("Asia/Shanghai"))
    today = now.date()

    # 按中国工作日判断，包含节假日与调休。
    if not is_workday(today):
        print(f"{today} 非工作日，跳过推送")
        return None

    title, body, ending = select_content(today)

    weekdays = [
        "周一",
        "周二",
        "周三",
        "周四",
        "周五",
        "周六",
        "周日",
    ]

    date_str = now.strftime("%Y年%m月%d日")
    weekday_str = weekdays[now.weekday()]
    time_str = now.strftime("%H:%M")

    return {
        "msg_type": "interactive",
        "card": {
            "config": {
                "wide_screen_mode": True,
            },
            "header": {
                "title": {
                    "tag": "plain_text",
                    "content": title,
                },
                "template": "purple",
            },
            "elements": [
                {
                    "tag": "div",
                    "text": {
                        "tag": "lark_md",
                        "content": (
                            f"**📅 {date_str}　"
                            f"{weekday_str}　{time_str}**"
                        ),
                    },
                },
                {
                    "tag": "div",
                    "text": {
                        "tag": "plain_text",
                        "content": body,
                    },
                },
                {
                    "tag": "hr",
                },
                {
                    "tag": "div",
                    "text": {
                        "tag": "plain_text",
                        "content": ending,
                    },
                },
            ],
        },
    }


def send_to_feishu(card):
    # 一次脚本运行只发送一次请求，不自动重试。
    try:
        response = requests.post(
            FEISHU_WEBHOOK,
            json=card,
            timeout=15,
        )
    except requests.RequestException as error:
        raise RuntimeError(
            f"飞书请求异常：{type(error).__name__}。"
            "请先检查群里是否收到，再决定是否重跑。"
        ) from None

    if response.status_code != 200:
        raise RuntimeError(
            f"飞书 HTTP 错误：{response.status_code}"
        )

    try:
        result = response.json()
    except ValueError:
        raise RuntimeError(
            "飞书返回的内容不是有效 JSON"
        ) from None

    if not isinstance(result, dict):
        raise RuntimeError("飞书返回格式异常")

    code = result.get(
        "code",
        result.get("StatusCode"),
    )

    if code != 0:
        raise RuntimeError(
            f"飞书推送失败，错误码：{code}"
        )

    print("飞书下班卡片推送成功")


def main():
    card = build_card()

    if card is not None:
        send_to_feishu(card)

    print("完成")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"运行失败：{error}")
        sys.exit(1)
